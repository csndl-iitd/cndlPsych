// Embed the AprilTag images (assets/tag_N.png, tag36h11 ids 0-3) as data URIs in
// framework/stage/tag-images.js, so the overlay needs no extra files.
//
//   node tools/gen-tags.js
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
const entries = [0, 1, 2, 3].map((id) => `  ${id}: 'data:image/png;base64,${readFileSync(join(root, 'assets', `tag_${id}.png`)).toString('base64')}',`);
writeFileSync(join(root, 'framework', 'stage', 'tag-images.js'), `// GENERATED by tools/gen-tags.js from assets/tag_N.png: do not edit.
// AprilTag family tag36h11, ids 0-3, as data URIs.
export const TAG36H11 = {
${entries.join('\n')}
};
`);
console.log('wrote framework/stage/tag-images.js');
